CREATE SCHEMA IF NOT EXISTS m25_legacy;
CREATE TABLE IF NOT EXISTS m25_legacy.dh_m15_checkpoints (
 thread_id VARCHAR(128) NOT NULL,
 checkpoint_ns VARCHAR(128) NOT NULL,
 checkpoint_id VARCHAR(64) NOT NULL,
 parent_id VARCHAR(64) NULL,
 checkpoint_type VARCHAR(32) NOT NULL,
 checkpoint BYTEA NOT NULL,
 metadata_type VARCHAR(32) NOT NULL,
 metadata BYTEA NOT NULL,
 PRIMARY KEY (thread_id,checkpoint_ns,checkpoint_id)
);
CREATE TABLE IF NOT EXISTS m25_legacy.dh_m15_checkpoint_writes (
 thread_id VARCHAR(128) NOT NULL,
 checkpoint_ns VARCHAR(128) NOT NULL,
 checkpoint_id VARCHAR(64) NOT NULL,
 task_id VARCHAR(128) NOT NULL,
 write_index INT NOT NULL,
 channel VARCHAR(128) NOT NULL,
 value_type VARCHAR(32) NOT NULL,
 value BYTEA NOT NULL,
 task_path TEXT NOT NULL,
 PRIMARY KEY (thread_id,checkpoint_ns,checkpoint_id,task_id,write_index)
);
CREATE TABLE IF NOT EXISTS dh_m15_operations (
 operation_id VARCHAR(128) PRIMARY KEY,
 run_id VARCHAR(32) NOT NULL,
 question_id VARCHAR(32) NOT NULL,
 status VARCHAR(32) NOT NULL,
 approval_status VARCHAR(32) NOT NULL,
 expires_at TIMESTAMPTZ NOT NULL,
 body JSON NOT NULL,
 lease_token VARCHAR(32) NULL,
 lease_until TIMESTAMPTZ NULL,
 CONSTRAINT uq_m15_run UNIQUE (run_id)
);
CREATE TABLE IF NOT EXISTS dh_m15_audit (
 event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 operation_id VARCHAR(128) NOT NULL,
 kind VARCHAR(32) NOT NULL,
 body JSON NOT NULL,
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS dh_m15_synthetic_effects (
 operation_id VARCHAR(128) PRIMARY KEY,
 binding_hash VARCHAR(64) NOT NULL,
 body JSON NOT NULL,
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS dh_m15_synthetic_calls (
 call_id VARCHAR(32) PRIMARY KEY,
 operation_id VARCHAR(128) NOT NULL,
 kind VARCHAR(32) NOT NULL,
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS ix_m15_question ON dh_m15_operations (question_id,status);
CREATE INDEX IF NOT EXISTS ix_m15_audit ON dh_m15_audit (operation_id,event_id);
CREATE INDEX IF NOT EXISTS ix_m15_calls ON dh_m15_synthetic_calls (operation_id,kind);
