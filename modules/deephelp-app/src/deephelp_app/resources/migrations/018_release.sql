CREATE TABLE IF NOT EXISTS dh_m18_releases (
 release_hash VARCHAR(64) PRIMARY KEY,
 version VARCHAR(128) NOT NULL UNIQUE,
 state VARCHAR(16) NOT NULL DEFAULT 'READY',
 body JSON NOT NULL,
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS dh_m18_active (
 channel VARCHAR(128) PRIMARY KEY,
 revision BIGINT NOT NULL DEFAULT 0 CHECK (revision >= 0),
 active_hash VARCHAR(64) NULL,
 previous_hash VARCHAR(64) NULL
);
CREATE TABLE IF NOT EXISTS dh_m18_run_releases (
 run_id VARCHAR(32) PRIMARY KEY,
 release_hash VARCHAR(64) NOT NULL
);
CREATE TABLE IF NOT EXISTS dh_m18_release_events (
 event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 channel VARCHAR(128) NOT NULL,
 revision BIGINT NOT NULL CHECK (revision >= 0),
 active_hash VARCHAR(64) NOT NULL,
 previous_hash VARCHAR(64) NULL,
 CONSTRAINT uq_m18_switch UNIQUE (channel,revision)
);

CREATE INDEX IF NOT EXISTS ix_m18_release_ref ON dh_m18_run_releases (release_hash);
