CREATE TABLE IF NOT EXISTS dh_m10_sessions (
 tenant_id VARCHAR(128) NOT NULL,
 user_id VARCHAR(128) NOT NULL,
 session_id VARCHAR(128) NOT NULL,
 generation BIGINT NOT NULL DEFAULT 0 CHECK (generation >= 0),
 PRIMARY KEY (tenant_id,user_id,session_id)
);
CREATE TABLE IF NOT EXISTS dh_m10_members (
 tenant_id VARCHAR(128) NOT NULL,
 user_id VARCHAR(128) NOT NULL,
 session_id VARCHAR(128) NOT NULL,
 channel VARCHAR(128) NOT NULL,
 message_id VARCHAR(128) NOT NULL,
 question_id VARCHAR(32) NOT NULL,
 occurred_at TIMESTAMPTZ NOT NULL,
 PRIMARY KEY (tenant_id,user_id,channel,message_id)
);
CREATE TABLE IF NOT EXISTS dh_m10_outbox (
 event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 question_id VARCHAR(32) NOT NULL,
 version BIGINT NOT NULL CHECK (version >= 0),
 body JSON NOT NULL,
 reason JSON NOT NULL,
 done BOOLEAN NOT NULL DEFAULT FALSE,
 attempts INT NOT NULL DEFAULT 0,
 lease_token VARCHAR(32) NULL,
 lease_until TIMESTAMPTZ NULL,
 last_error VARCHAR(64) NULL,
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT uq_m10_event_version UNIQUE (question_id,version)
);

CREATE INDEX IF NOT EXISTS ix_m10_history ON dh_m10_members (tenant_id,user_id,session_id,occurred_at);
CREATE INDEX IF NOT EXISTS ix_m10_question ON dh_m10_members (question_id,occurred_at);
CREATE INDEX IF NOT EXISTS ix_m10_pending ON dh_m10_outbox (done,event_id);
